const KEY = "meridian_lang_v1";

export const I18n = {
  lang: null,
  get() {
    if (this.lang) return this.lang;
    try {
      this.lang = localStorage.getItem(KEY);
    } catch (e) {
      this.lang = null;
    }
    return this.lang;
  },
  set(code) {
    if (!dict[code]) return;
    this.lang = code;
    try {
      localStorage.setItem(KEY, code);
    } catch (e) {}
  },
  clear() {
    this.lang = null;
    try {
      localStorage.removeItem(KEY);
    } catch (e) {}
  },
  bcp47() {
    const l = LANGS.find((x) => x.code === (this.get() || "en"));
    return l ? l.bcp47 : "en-IN";
  },
};

export function t(key) {
  const l = I18n.get() || "en";
  return (dict[l] && dict[l][key]) || dict.en[key] || key;
}
